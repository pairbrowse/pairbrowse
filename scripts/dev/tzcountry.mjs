#!/usr/bin/env node
// A dev tool, not plugin code: writes scripts/rules/tzcountry.mjs, the time zones of each country,
// from the IANA tz database's zone.tab (public domain; on macOS and most Linux systems at
// /usr/share/zoneinfo/zone.tab) and, when it is there too, zone1970.tab (a zone shared by several
// countries lists each of them). Every zone is also listed under the name this Node's Intl gives it
// (Asia/Ho_Chi_Minh is Asia/Saigon there), since that is the name a browser and the helper report.
//   node scripts/dev/tzcountry.mjs [zoneinfo folder]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2] || "/usr/share/zoneinfo";
const out = fileURLToPath(new URL("../rules/tzcountry.mjs", import.meta.url));
const rows = (file) => (existsSync(join(dir, file)) ? readFileSync(join(dir, file), "utf8").split("\n").filter((l) => l && !l.startsWith("#")).map((l) => l.split("\t")) : []);

const byZone = new Map(); // zone -> Set of country codes
const add = (zone, codes) => { const s = byZone.get(zone) || new Set(); for (const c of codes) if (/^[A-Z]{2}$/.test(c)) s.add(c); byZone.set(zone, s); };
const tab = rows("zone.tab");
if (!tab.length) throw new Error(`no zone.tab in ${dir}`);
for (const [code, , zone] of tab) add(zone, [code]);
for (const [codes, , zone] of rows("zone1970.tab")) add(zone, codes.split(","));
// Intl's own name for each zone (an older spelling some systems still report).
const intlName = (zone) => { try { return new Intl.DateTimeFormat("en", { timeZone: zone }).resolvedOptions().timeZone; } catch { return zone; } };
for (const [zone, codes] of [...byZone]) { const n = intlName(zone); if (n !== zone && n.includes("/")) add(n, codes); }

const byCountry = new Map();
for (const [zone, codes] of byZone) for (const c of codes) byCountry.set(c, [...(byCountry.get(c) || []), zone]);
const version = existsSync(join(dir, "+VERSION")) ? readFileSync(join(dir, "+VERSION"), "utf8").trim() : "";
const lines = [...byCountry].sort(([a], [b]) => a.localeCompare(b)).map(([c, zones]) => `  ${c}: "${[...new Set(zones)].sort().join(" ")}",`);
writeFileSync(out, `// Generated by scripts/dev/tzcountry.mjs from the IANA tz database's zone.tab${version ? ` (${version})` : ""}
// (public domain); do not edit by hand. Each country's time zones, with the names Intl reports
// for them too. Pure, no imports.
const ZONES = {
${lines.join("\n")}
};

// zone -> the country codes it is used in.
const BY_ZONE = new Map();
for (const [country, zones] of Object.entries(ZONES)) for (const z of zones.split(" ")) BY_ZONE.set(z, [...(BY_ZONE.get(z) || []), country]);

// The countries time zone \`zone\` is used in (two capital letters each), or null when it isn't a
// country's zone (UTC, Etc/GMT+5, a name not known here).
export function countriesOf(zone) {
  if (typeof zone !== "string" || !zone) return null;
  let list = BY_ZONE.get(zone);
  if (!list) {
    try { list = BY_ZONE.get(new Intl.DateTimeFormat("en", { timeZone: zone }).resolvedOptions().timeZone); } catch { list = undefined; }
  }
  return list ? [...list] : null;
}
`);
console.log(`wrote ${out}: ${byZone.size} zones, ${byCountry.size} countries`);
